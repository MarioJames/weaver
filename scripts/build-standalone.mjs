// Standalone executables for a GitHub Release: one file per platform with the
// renderer, the agents-weaver skill and the mock worker embedded, no Node or npm needed on the target.
// Run after `npm run build` (needs dist/renderer). Needs Bun on PATH to compile.
//   node scripts/build-standalone.mjs           # this machine's platform only
//   node scripts/build-standalone.mjs --all     # every published target
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { join, relative, resolve, sep } from 'node:path';

const repo = resolve(import.meta.dirname, '..');
const TARGETS = { 'linux-x64': 'bun-linux-x64', 'linux-arm64': 'bun-linux-arm64', 'darwin-arm64': 'bun-darwin-arm64' };
const MOCK_WORKER_ARG = '__weaver-mock-worker';
const all = process.argv.includes('--all');
const host = `${process.platform}-${process.arch}`;
const targets = all ? Object.keys(TARGETS) : [host];
for (const target of targets) if (!TARGETS[target]) throw new Error(`No standalone target for ${target}; published targets: ${Object.keys(TARGETS).join(', ')}`);
if (spawnSync('bun', ['--version'], { stdio: 'ignore' }).status !== 0) throw new Error('Bun is required to compile standalone executables: https://bun.sh');

const rendererRoot = join(repo, 'dist/renderer');
async function files(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await files(full));
    else out.push(full);
  }
  return out;
}
let rendererFiles;
try { rendererFiles = await files(rendererRoot); } catch { throw new Error('dist/renderer is missing; run `npm run build` first'); }
if (!rendererFiles.some(file => file.endsWith(`${sep}index.html`))) throw new Error('dist/renderer has no index.html; run `npm run build` first');
const renderer = {};
for (const file of rendererFiles) renderer[relative(rendererRoot, file).split(sep).join('/')] = (await readFile(file)).toString('base64');

const skillRoot = join(repo, 'skills/agents-weaver');
const skill = {};
for (const file of await files(skillRoot)) skill[relative(skillRoot, file).split(sep).join('/')] = (await readFile(file)).toString('base64');
if (!skill['SKILL.md']) throw new Error('skills/agents-weaver/SKILL.md is missing');

const work = join(repo, '.build/standalone');
await rm(work, { recursive: true, force: true });
await mkdir(work, { recursive: true });
const entry = join(work, 'entry.ts');
const source = (path) => JSON.stringify(join(repo, path));
await writeFile(entry, `// Generated by scripts/build-standalone.mjs. Do not edit.
import { runCLI } from ${source('src/cli/main.ts')};
import { setEmbeddedApp } from ${source('src/main/embedded.ts')};
const RENDERER: Record<string, string> = ${JSON.stringify(renderer)};
const SKILL: Record<string, string> = ${JSON.stringify(skill)};
const decode = (map: Record<string, string>) => new Map(Object.entries(map).map(([path, body]) => [path, Buffer.from(body, 'base64')]));
if (process.argv[2] === ${JSON.stringify(MOCK_WORKER_ARG)}) {
  await import(${source('scripts/mock-worker.mjs')});
} else {
  setEmbeddedApp({ renderer: decode(RENDERER), skill: decode(SKILL), mockWorkerArg: ${JSON.stringify(MOCK_WORKER_ARG)} });
  process.exitCode = await runCLI(process.argv.slice(2));
}
`);

const out = join(repo, 'dist/release');
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
const sums = [];
for (const target of targets) {
  const name = `weaver-${target}`;
  const outfile = join(out, name);
  // vite is only imported by `weaver web --dev`, which a standalone executable refuses.
  const result = spawnSync('bun', ['build', '--compile', '--minify', `--target=${TARGETS[target]}`, '--external', 'vite', entry, '--outfile', outfile], { cwd: repo, stdio: 'inherit' });
  if (result.status !== 0) throw new Error(`bun build failed for ${target}`);
  sums.push(`${createHash('sha256').update(await readFile(outfile)).digest('hex')}  ${name}`);
  console.log(`built dist/release/${name}`);
}
await writeFile(join(out, 'SHA256SUMS'), `${sums.join('\n')}\n`);
await rm(join(repo, '.build'), { recursive: true, force: true });
